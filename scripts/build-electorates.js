#!/usr/bin/env node
// Validates data/nz/electorates/*.json, resolves each candidate's cells against the
// party scores in data/nz/parties.js, and writes data/nz/electorates.js.
//
// A candidate cell has a "basis":
//   "candidate" - scored from the candidate's own statements or record (score given here)
//   "party"     - no direct evidence; inherits the party's score with confidence one step lower
//   "none"      - no party score and no direct evidence; unscored
// Usage: node scripts/build-electorates.js [--check]

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC_DIR = path.join(ROOT, "data", "nz", "electorates");
const OUT = path.join(ROOT, "data", "nz", "electorates.js");
const { DIMENSIONS } = require(path.join(ROOT, "js", "data.js"));
const PARTIES = require(path.join(ROOT, "data", "nz", "parties.js"));
const DIM_IDS = DIMENSIONS.map((d) => d.id);
const DIM_BY_ID = Object.fromEntries(DIMENSIONS.map((d) => [d.id, d]));
const lean = (score, d) => (score > 0 ? `${score} towards ${d.poles[0]}` : score < 0 ? `${-score} towards ${d.poles[1]}` : "0, balanced");
const CONFIDENCE = ["high", "medium", "low"];
const DOWNGRADE = { high: "medium", medium: "low", low: "low" };

function resolve(electorate, file) {
  const errors = [];
  const err = (m) => errors.push(`${path.basename(file)}: ${m}`);
  const partyById = {};
  PARTIES.parties.forEach((p) => { partyById[p.id] = p; });
  ["id", "name", "election", "assessedAt", "status", "context", "candidates"].forEach((k) => { if (!(k in electorate)) err(`missing field ${k}`); });
  if (electorate.id !== path.basename(file, ".json")) err("id does not match filename");
  const out = { ...electorate, candidates: [] };
  for (const c of electorate.candidates || []) {
    ["id", "name", "partyName", "bio", "sources"].forEach((k) => { if (!(k in c)) err(`${c.id || "?"}: missing ${k}`); });
    if (c.party && !partyById[c.party]) err(`${c.id}: unknown party id ${c.party}`);
    const party = c.party ? partyById[c.party] : null;
    const dims = {};
    for (const id of DIM_IDS) {
      const given = (c.dimensions || {})[id];
      if (given && given.basis === "candidate") {
        if (!Number.isInteger(given.score) || given.score < -100 || given.score > 100) err(`${c.id}/${id}: score must be an integer -100..100`);
        if (!CONFIDENCE.includes(given.confidence)) err(`${c.id}/${id}: bad confidence`);
        if (!given.rationale || given.rationale.length < 40) err(`${c.id}/${id}: rationale missing or too short`);
        if (!Array.isArray(given.sources) || !given.sources.length) err(`${c.id}/${id}: candidate-based cell needs sources`);
        (given.sources || []).forEach((s) => { if (s.archived && !fs.existsSync(path.join(ROOT, s.archived))) err(`${c.id}/${id}: missing ${s.archived}`); });
        dims[id] = { ...given, basis: "candidate" };
      } else if (party && party.dimensions[id] && typeof party.dimensions[id].score === "number") {
        const pc = party.dimensions[id];
        dims[id] = {
          score: pc.score, confidence: DOWNGRADE[pc.confidence], basis: "party",
          rationale: (given && given.note ? given.note + " " : "") +
            `No direct evidence of ${c.name}'s own position on this dimension; inherits ${party.short}'s score (${lean(pc.score, DIM_BY_ID[id])}, ${pc.confidence} confidence) with confidence lowered one step. ${party.short}: ${pc.rationale}`,
          sources: pc.sources
        };
      } else {
        dims[id] = { score: null, confidence: "low", basis: "none",
          rationale: (given && given.note ? given.note + " " : "") + `No party score and no direct evidence for ${c.name} on this dimension.`, sources: [] };
      }
    }
    out.candidates.push({ ...c, dimensions: dims, short: c.short || c.name.split(" ").slice(-1)[0], colour: c.colour || (party ? party.colour : "#8a8983") });
  }
  return { out, errors };
}

function main() {
  const check = process.argv.includes("--check");
  const files = fs.existsSync(SRC_DIR) ? fs.readdirSync(SRC_DIR).filter((f) => f.endsWith(".json")).sort() : [];
  const electorates = [];
  let errors = [];
  for (const f of files) {
    const full = path.join(SRC_DIR, f);
    let e;
    try { e = JSON.parse(fs.readFileSync(full, "utf8")); } catch (x) { errors.push(`${f}: invalid JSON (${x.message})`); continue; }
    const { out, errors: errs } = resolve(e, full);
    errors = errors.concat(errs);
    electorates.push(out);
  }
  if (errors.length) { console.error("Validation failed:\n  " + errors.join("\n  ")); process.exit(1); }
  const body = "// Generated by scripts/build-electorates.js from data/nz/electorates/*.json and data/nz/parties.js. Do not edit by hand.\n" +
    "var ELECTORATES_NZ = " + JSON.stringify({ generatedAt: new Date().toISOString().slice(0, 10), electorates }, null, 2) + ";\n" +
    "if (typeof module !== \"undefined\") { module.exports = ELECTORATES_NZ; }\n";
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    const strip = (s) => s.replace(/"generatedAt": "[^"]*"/, "");
    if (strip(current) !== strip(body)) { console.error(`${path.relative(ROOT, OUT)} is out of date; run node scripts/build-electorates.js`); process.exit(1); }
    console.log(`OK: ${electorates.length} electorates valid, ${path.relative(ROOT, OUT)} in sync`);
    return;
  }
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${electorates.map((e) => `${e.name} (${e.candidates.length} candidates)`).join(", ")}`);
}

main();
